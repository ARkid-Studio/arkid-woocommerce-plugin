<?php
/**
 * Regenerates includes/Matching/nfd-table.php from the ICU that this PHP uses.
 *
 * The table is what `Matching\Decomposition` falls back to on a host without
 * ext-intl: every character that Unicode's canonical decomposition (NFD) splits
 * into letters and combining marks, mapped to what is left of it once the
 * marks are removed. The maintainer runs this when ARkid raises the Unicode
 * version it cares about; Unicode never changes a canonical decomposition, so
 * a table made with an older ICU stays right and only misses newer characters.
 *
 *     php bin/generate-nfd-table.php > includes/Matching/nfd-table.php
 *
 * Needs ext-intl and ext-pcre. Hangul syllables are left out (their NFD is a
 * run of conjoining letters, not marks, and `Decomposition` computes it).
 *
 * @package Arkid\CatalogueLink
 */

declare( strict_types = 1 );

if ( ! class_exists( 'Normalizer' ) ) {
	fwrite( STDERR, "ext-intl is needed to generate the table.\n" ); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_fwrite
	exit( 1 );
}

/** @var array<string, array<int, int>> $groups Result by the code points that decompose to it. */
$groups = array();

for ( $code_point = 0x80; $code_point <= 0x10FFFF; $code_point++ ) {
	if ( ( $code_point >= 0xD800 && $code_point <= 0xDFFF ) || ( $code_point >= 0xAC00 && $code_point <= 0xD7A3 ) ) {
		continue;
	}

	$char = IntlChar::chr( $code_point );
	if ( null === $char || 1 === preg_match( '/^\p{M}$/u', $char ) ) {
		// A mark is removed wherever it stands; the table is for what it leaves.
		continue;
	}

	$decomposed = Normalizer::normalize( $char, Normalizer::FORM_D );
	if ( false === $decomposed ) {
		continue;
	}
	$stripped = preg_replace( '/\p{M}+/u', '', $decomposed );
	if ( null === $stripped || $stripped === $char ) {
		continue;
	}

	$groups[ $stripped ][] = $code_point;
}

/**
 * @param string $text A string of one or more characters.
 */
function arkid_escape( string $text ): string {
	$out = '';
	foreach ( preg_split( '//u', $text, -1, PREG_SPLIT_NO_EMPTY ) ?: array() as $char ) {
		$out .= sprintf( '\u{%X}', IntlChar::ord( $char ) );
	}

	return $out;
}

ksort( $groups, SORT_STRING );

echo "<?php\n";
echo "/**\n";
echo " * What each character that Unicode splits into letters and combining marks is\n";
echo " * left with once the marks are removed: the fallback of `Matching\\Decomposition`\n";
echo ' * for a host without ext-intl. Generated by bin/generate-nfd-table.php from ICU ' . INTL_ICU_VERSION . ",\n";
echo ' * Unicode ' . implode( '.', array_slice( IntlChar::getUnicodeVersion(), 0, 3 ) ) . ". Do not edit by hand.\n";
echo " *\n";
echo " * Each entry is the text that is left, and the characters that leave it.\n";
echo " *\n";
echo " * @package Arkid\\CatalogueLink\n";
echo " */\n\n";
echo "declare( strict_types = 1 );\n\n";
echo "defined( 'ABSPATH' ) || exit;\n\n";
echo "return array(\n";
foreach ( $groups as $left => $code_points ) {
	$sources = '';
	foreach ( $code_points as $code_point ) {
		$sources .= sprintf( '\u{%X}', $code_point );
	}
	$left = (string) $left;
	$key  = 1 === preg_match( '/^[A-Za-z0-9]$/', $left ) ? "'" . $left . "'" : '"' . arkid_escape( $left ) . '"';
	echo "\t" . $key . ' => "' . $sources . "\",\n";
}
echo ");\n";
